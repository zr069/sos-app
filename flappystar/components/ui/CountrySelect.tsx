interface CountrySelectProps {
  value: string;
  onChange: (code: string) => void;
  placeholder?: string;
  error?: string;
}

export default function CountrySelect({
  value,
  onChange,
  placeholder = 'Select country',
  error,
}: CountrySelectProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [search, setSearch] = useState('');
  const containerRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const selectedCountry = countries.find((c) => c.code === value);

  const filteredCountries = countries.filter(
    (country) =>
      country.name.toLowerCase().includes(search.toLowerCase()) ||
      country.code.toLowerCase().includes(search.toLowerCase())
  );

  // Close on click outside
  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (
        containerRef.current &&
        !containerRef.current.contains(event.target as Node)
      ) {
        setIsOpen(false);
        setSearch('');
      }
    };

    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  // Focus input when opening
  useEffect(() => {
    if (isOpen && inputRef.current) {
      inputRef.current.focus();
    }
  }, [isOpen]);

  const handleSelect = (country: Country) => {
    onChange(country.code);
    setIsOpen(false);
    setSearch('');
  };

  return (
    <div ref={containerRef} className="relative">
      <button
        type="button"
        onClick={() => setIsOpen(!isOpen)}
        className={`w-full px-4 py-3 bg-surface border rounded-lg text-left flex items-center gap-3 transition-colors ${
          error
            ? 'border-red-500'
            : isOpen
            ? 'border-primary'
            : 'border-surface-border hover:border-primary/50'
        }`}
      >
        {selectedCountry ? (
          <>
            <span className="text-xl">{selectedCountry.flag}</span>
            <span className="text-white">{selectedCountry.name}</span>
          </>
        ) : (
          <span className="text-text-muted">{placeholder}</span>
        )}
        <svg
          className={`w-5 h-5 text-text-muted ml-auto transition-transform ${
            isOpen ? 'rotate-180' : ''
          }`}
          fill="none"
          stroke="currentColor"
          viewBox="0 0 24 24"
        >
          <path
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth={2}
            d="M19 9l-7 7-7-7"
          />
        </svg>
      </button>

      {error && <p className="mt-1 text-sm text-red-500">{error}</p>}

      <AnimatePresence>
        {isOpen && (
          <motion.div
            initial={{ opacity: 0, y: -10 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -10 }}
            className="absolute z-50 w-full mt-2 bg-background border border-surface-border rounded-lg shadow-xl overflow-hidden"
          >
            {/* Search input */}
            <div className="p-2 border-b border-surface-border">
              <input
                ref={inputRef}
                type="text"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                placeholder="Search..."
                className="w-full px-3 py-2 bg-surface border border-surface-border rounded-lg text-white placeholder:text-text-muted focus:outline-none focus:border-primary"
              />
            </div>

            {/* Country list */}
            <div className="max-h-60 overflow-y-auto">
              {filteredCountries.length === 0 ? (
                <div className="px-4 py-3 text-text-muted text-center">
                  No countries found
                </div>
              ) : (
                filteredCountries.map((country) => (
                  <button
                    key={country.code}
                    type="button"
                    onClick={() => handleSelect(country)}
                    className={`w-full px-4 py-2.5 flex items-center gap-3 hover:bg-surface transition-colors ${
                      value === country.code ? 'bg-surface' : ''
                    }`}
                  >
                    <span className="text-xl">{country.flag}</span>
                    <span className="text-white">{country.name}</span>
                    <span className="text-text-muted text-sm ml-auto">
                      {country.code}
                    </span>
                  </button>
                ))
              )}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

// Helper to get flag by country code
export function getCountryFlag(code: string): string {
  const country = countries.find((c) => c.code === code);
  return country?.flag || '🏳️';
}

